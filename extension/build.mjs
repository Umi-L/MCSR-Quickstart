// Build script for the MCSR Quickstart extension.
//
//   node build.mjs              production build (minified) -> dist/chrome, dist/firefox
//   node build.mjs --watch      dev build with inline sourcemaps, rebuilds on change
//   node build.mjs --gen-only   only regenerate src/generated/sites.ts (used by typecheck)
//   node build.mjs --package    production build + zip both targets into ../release/
//
// ../shared/sites.json is the single source of truth for supported sites: it fills the
// manifests' content_scripts matches / host_permissions and generates the SiteId type.

import * as esbuild from 'esbuild';
import { zipSync } from 'fflate';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SITES_JSON = path.resolve(ROOT, '../shared/sites.json');
const MANIFEST_BASE = path.join(ROOT, 'manifest.base.json');
const GENERATED_SITES = path.join(ROOT, 'src/generated/sites.ts');
const POPUP_HTML = path.join(ROOT, 'src/popup/popup.html');
const DIST = path.join(ROOT, 'dist');
const RELEASE = path.resolve(ROOT, '../release');
const TARGETS = /** @type {const} */ (['chrome', 'firefox']);

const LOCAL_APP_PERMISSION = 'http://127.0.0.1/*';
const GECKO_ID = 'mcsr-quickstart@mcsr-quickstart.local';
const GECKO_MIN_VERSION = '128.0';

const args = new Set(process.argv.slice(2));
const watch = args.has('--watch');
const genOnly = args.has('--gen-only');
const pack = args.has('--package');

// ---------------------------------------------------------------------------
// sites.json

/** @typedef {{ id: string; name: string; matches: string[] }} Site */

/** @returns {Site[]} */
function readSites() {
  const raw = JSON.parse(fs.readFileSync(SITES_JSON, 'utf8'));
  if (!Array.isArray(raw) || raw.length === 0) throw new Error('sites.json must be a non-empty array');
  const ids = new Set();
  return raw.map((s, i) => {
    const where = `sites.json[${i}]`;
    if (typeof s !== 'object' || s === null) throw new Error(`${where} must be an object`);
    if (typeof s.id !== 'string' || !/^[a-z][a-z0-9_]*$/.test(s.id)) throw new Error(`${where}.id must match /^[a-z][a-z0-9_]*$/`);
    if (ids.has(s.id)) throw new Error(`${where}.id "${s.id}" is duplicated`);
    ids.add(s.id);
    if (typeof s.name !== 'string' || s.name.length === 0) throw new Error(`${where}.name must be a non-empty string`);
    if (!Array.isArray(s.matches) || s.matches.length === 0 || !s.matches.every((m) => typeof m === 'string' && /^https?:\/\/[^/]+\/.*$/.test(m))) {
      throw new Error(`${where}.matches must be a non-empty array of match patterns like "https://example.com/*"`);
    }
    return { id: s.id, name: s.name, matches: s.matches };
  });
}

/** Writes src/generated/sites.ts only when its content changes (keeps watch mode quiet). */
function generateSitesModule(sites) {
  const body =
    '// GENERATED by build.mjs from ../shared/sites.json. Do not edit by hand.\n\n' +
    `export const SITES = ${JSON.stringify(sites, null, 2)} as const;\n\n` +
    "export type SiteId = (typeof SITES)[number]['id'];\n";
  const current = fs.existsSync(GENERATED_SITES) ? fs.readFileSync(GENERATED_SITES, 'utf8') : '';
  if (current !== body) {
    fs.mkdirSync(path.dirname(GENERATED_SITES), { recursive: true });
    fs.writeFileSync(GENERATED_SITES, body);
  }
}

// ---------------------------------------------------------------------------
// manifests + static files

function readVersion() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
}

/** @param {'chrome' | 'firefox'} target @param {Site[]} sites */
function buildManifest(target, sites) {
  const base = JSON.parse(fs.readFileSync(MANIFEST_BASE, 'utf8'));
  const matches = [...new Set(sites.flatMap((s) => s.matches))];
  const manifest = {
    ...base,
    version: readVersion(),
    host_permissions: [...matches, LOCAL_APP_PERMISSION],
    content_scripts: base.content_scripts.map((cs) => ({ ...cs, matches })),
    background:
      target === 'chrome'
        ? { service_worker: 'background.js' }
        : { scripts: ['background.js'] },
  };
  if (target === 'firefox') {
    manifest.browser_specific_settings = {
      gecko: { id: GECKO_ID, strict_min_version: GECKO_MIN_VERSION },
    };
  }
  return manifest;
}

function writeStatic(sites) {
  for (const target of TARGETS) {
    const dir = path.join(DIST, target);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(buildManifest(target, sites), null, 2) + '\n');
    fs.copyFileSync(POPUP_HTML, path.join(dir, 'popup.html'));
  }
}

// ---------------------------------------------------------------------------
// esbuild

/** Writes the in-memory esbuild output into every target dir, plus manifests and html. */
const emitPlugin = {
  name: 'emit-targets',
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length > 0) return;
      const sites = readSites();
      writeStatic(sites);
      const outdir = build.initialOptions.outdir;
      for (const file of result.outputFiles ?? []) {
        const rel = path.relative(outdir, file.path);
        for (const target of TARGETS) {
          const dest = path.join(DIST, target, rel);
          fs.mkdirSync(path.dirname(dest), { recursive: true });
          fs.writeFileSync(dest, file.contents);
        }
      }
      console.log(`[build] ${new Date().toLocaleTimeString()} wrote dist/chrome and dist/firefox`);
    });
  },
};

/** @returns {esbuild.BuildOptions} */
function esbuildOptions() {
  return {
    absWorkingDir: ROOT,
    entryPoints: {
      background: 'src/background.ts',
      content: 'src/core/inject.ts',
      popup: 'src/popup/popup.ts',
    },
    outdir: path.join(DIST, '.out'),
    bundle: true,
    format: 'iife',
    target: ['chrome110', 'firefox128'],
    minify: !watch,
    sourcemap: watch ? 'inline' : false,
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
    plugins: [emitPlugin],
  };
}

function zipDir(dir) {
  /** @type {Record<string, Uint8Array>} */
  const files = {};
  const walk = (d) => {
    for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, entry.name);
      if (entry.isDirectory()) walk(full);
      else files[path.relative(dir, full).split(path.sep).join('/')] = fs.readFileSync(full);
    }
  };
  walk(dir);
  return zipSync(files, { level: 9 });
}

// ---------------------------------------------------------------------------

async function main() {
  const sites = readSites();
  generateSitesModule(sites);
  if (genOnly) return;

  fs.rmSync(DIST, { recursive: true, force: true });

  if (watch) {
    const ctx = await esbuild.context(esbuildOptions());
    await ctx.watch();
    // Files outside the esbuild module graph: regenerate and rebuild when they change.
    for (const file of [SITES_JSON, MANIFEST_BASE, POPUP_HTML]) {
      fs.watchFile(file, { interval: 300 }, () => {
        try {
          generateSitesModule(readSites());
          void ctx.rebuild().catch(() => {});
        } catch (err) {
          console.error(`[build] ${err instanceof Error ? err.message : err}`);
        }
      });
    }
    console.log('[build] watching for changes (Ctrl+C to stop)');
    return;
  }

  await esbuild.build(esbuildOptions());

  if (pack) {
    fs.mkdirSync(RELEASE, { recursive: true });
    const version = readVersion();
    for (const target of TARGETS) {
      const out = path.join(RELEASE, `mcsr-quickstart-${target}-${version}.zip`);
      fs.writeFileSync(out, zipDir(path.join(DIST, target)));
      console.log(`[package] ${path.relative(process.cwd(), out)}`);
    }
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
